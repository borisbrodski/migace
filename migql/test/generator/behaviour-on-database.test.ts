import { describe, expect, test } from 'vitest';
import { compare, differencesText } from '@migace/core';
import { createMigql, lines } from '../support.js';
import { createBookshopDatabase } from './database.js';

const { parse } = createMigql();
const { bookshop, exec, rows, run, model } = createBookshopDatabase();

/** Runs the generated PostgreSQL of a part with the given body. */
async function runPart(...body: string[]): Promise<void> {
    const document = await parse(lines('migration: 20260302-0900-x', 'parts:', '  - p:', ...body.map(line => '      ' + line)));
    expect(document).toHaveNoErrors();
    await run(document.parseResult.value);
}

const ORDER_STATUS = `
    create table order_status (id bigint generated by default as identity primary key, code varchar(20) not null unique, label varchar(50) not null);
    insert into order_status (id, code, label) values (1, 'OPEN', 'Open'), (2, 'PAID', 'Old label');
    alter table order_status alter column id restart with 10`;

const CUSTOMERS = `
    insert into customer (id, name, mail, created_at) values (1, 'Maria', 'maria@example.org', now()), (2, 'Jo', null, now())`;

// M3-AC-18
describe('Statements that change rows, on a database', () => {
    test('update changes the rows that the condition names', async () => {
        await bookshop(CUSTOMERS);

        await runPart('do: |', "  update customer c set name = upper(trim(c.name)) || '!' where c.mail is null");

        expect(await rows('select id, name from customer order by id')).toEqual([{ id: 1, name: 'Maria' }, { id: 2, name: 'JO!' }]);
    });

    test('delete removes the rows that the condition names', async () => {
        await bookshop(CUSTOMERS);

        await runPart('do: delete from customer where not exists (select 1 from customer c where c.mail is not null and c.id = customer.id)');

        expect(await rows('select id from customer')).toEqual([{ id: 1 }]);
    });

    test('insert with values adds one row, and next value takes a number from the sequence', async () => {
        await bookshop();

        await runPart('do: |', "  insert into customer (id, name, created_at) values (next value for bookshop_seq, 'It''s Jo', date '2026-01-31' + days(1))");

        expect(await rows("select id, name, created_at::date::text as day from customer")).toEqual([{ id: 1, name: "It's Jo", day: '2026-02-01' }]);
    });

    test('insert with select copies rows', async () => {
        await bookshop(CUSTOMERS, 'create table customer_copy (id bigint, name varchar(100))');

        await runPart('do: insert into customer_copy (id, name) select c.id, lower(c.name) from customer c where c.id > 1');

        expect(await rows('select id, name from customer_copy')).toEqual([{ id: 2, name: 'jo' }]);
    });

    test('insert in YAML form adds its rows', async () => {
        await bookshop(ORDER_STATUS);

        await runPart('insert:', '  into: order_status', '  rows:', "    - { id: 3, code: 'SHIPPED', label: 'Shipped' }", "    - { id: 4, code: 'CANCELLED', label: 'Cancelled' }");

        expect(await rows('select code from order_status order by id')).toEqual([{ code: 'OPEN' }, { code: 'PAID' }, { code: 'SHIPPED' }, { code: 'CANCELLED' }]);
    });

    // M3-AC-11
    test('upsert adds the rows that are missing and updates those that exist, and can run again', async () => {
        await bookshop(ORDER_STATUS);
        const body = ['upsert:', '  into: order_status', '  key: code', '  rows:', "    - { code: 'PAID', label: 'Paid' }", "    - { code: 'SHIPPED', label: 'Shipped' }"];

        await runPart(...body);
        await runPart(...body);

        expect(await rows('select code, label from order_status order by code')).toEqual([
            { code: 'OPEN', label: 'Open' }, { code: 'PAID', label: 'Paid' }, { code: 'SHIPPED', label: 'Shipped' },
        ]);
    });

    test('native SQL runs as it is written', async () => {
        await bookshop();

        await runPart('native:', '  postgresql: |', '    create index ix_book_author_search on book', '      using gin (author gin_trgm_ops);');

        expect((await model()).tables.find(table => table.name === 'book')!.indexes.map(index => index.name)).toContain('ix_book_author_search');
    });
});

// M3-AC-09
describe('ensure column on a database', () => {
    const noteType = async () => (await model()).tables.find(table => table.name === 'orders')!.columns.find(column => column.name === 'note');

    test('the column is missing: it is added', async () => {
        await bookshop();

        await runPart('do: ensure column orders.note varchar(500)');

        expect(await noteType()).toEqual({ name: 'note', type: 'character varying', typeDetails: '500', nullable: true });
    });

    test('the column is narrower: it is widened, and its values stay', async () => {
        await bookshop(
            'alter table orders add column note varchar(100)',
            "insert into customer (id, name, created_at) values (1, 'Jo', now())",
            "insert into orders (id, customer_id, status, created_at, total_cents, note) values (1, 1, 'OPEN', now(), 0, 'Ring twice')");

        await runPart('do: ensure column orders.note varchar(500)');

        expect(await noteType()).toMatchObject({ type: 'character varying', typeDetails: '500' });
        expect(await rows('select note from orders')).toEqual([{ note: 'Ring twice' }]);
    });

    test('the column matches: nothing happens', async () => {
        await bookshop('alter table orders add column note varchar(500)');
        const before = await model();

        await runPart('do: ensure column orders.note varchar(500)');

        expect(compare(before, await model())).toEqual([]);
    });

    test.each([
        ['wider', 'varchar(1000)', 'character varying(1000)'],
        ['of another type', 'integer', 'integer'],
        ['without a length', 'varchar', 'character varying'],
    ])('the column is %s: the part fails with a clear message', async (_what, type, shown) => {
        await bookshop(`alter table orders add column note ${type}`);

        await expect(runPart('do: ensure column orders.note varchar(500)')).rejects.toThrow(
            `ensure column orders.note varchar(500): the column exists as ${shown}. It can neither be kept nor widened.`);
    });

    test('a type without details is kept, and another type fails', async () => {
        await bookshop('alter table orders add column ship_by date', 'alter table orders add column due_by timestamp');

        await runPart('do: ensure column orders.ship_by date');
        await expect(runPart('do: ensure column orders.due_by date')).rejects.toThrow('the column exists as timestamp without time zone');
    });

    test('a number with precision is kept if it is the same', async () => {
        await bookshop('alter table book add column weight numeric(8, 3)');
        const before = await model();

        await runPart('do: ensure column book.weight numeric(8, 3)');

        expect(compare(before, await model())).toEqual([]);
        await expect(runPart('do: ensure column book.weight numeric(10, 3)')).rejects.toThrow('the column exists as numeric(8,3)');
    });
});

// M3-AC-19
describe('A form that does not lock for long leaves the same schema as the simple form', () => {
    test('set not null', async () => {
        await bookshop("insert into customer (id, name, mail, created_at) values (1, 'Jo', 'jo@example.org', now())");
        await exec('alter table customer alter column mail set not null');
        const simple = await model();
        await bookshop("insert into customer (id, name, mail, created_at) values (1, 'Jo', 'jo@example.org', now())");

        await runPart('do: alter table customer alter column mail set not null');

        expect(differencesText(compare(simple, await model()))).toBe('');
    });

    test('set not null fails in its second step when a row has no value, and the column stays optional', async () => {
        await bookshop("insert into customer (id, name, created_at) values (1, 'Jo', now())");

        await expect(runPart('do: alter table customer alter column mail set not null')).rejects.toThrow(/customer_mail_not_null/);

        expect((await model()).tables.find(table => table.name === 'customer')!.columns.find(column => column.name === 'mail')!.nullable).toBe(true);
    });

    test('a new foreign key', async () => {
        const review = 'create table review (id bigint primary key, book_id bigint not null)';
        await bookshop(review);
        await exec('alter table review add constraint fk_review_book foreign key (book_id) references book (id)');
        const simple = await model();
        await bookshop(review);

        await runPart('do: alter table review add constraint fk_review_book foreign key (book_id) references book (id)');

        expect(differencesText(compare(simple, await model()))).toBe('');
    });

    test('an index that is built concurrently', async () => {
        await bookshop();
        await exec('create index ix_book_author on book (author)');
        const simple = await model();
        await bookshop();

        await runPart('do: create index concurrently ix_book_author on book (author)');

        expect(differencesText(compare(simple, await model()))).toBe('');
    });
});
