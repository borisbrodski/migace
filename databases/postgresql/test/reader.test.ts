import { describe, expect, test } from 'vitest';
import type { SchemaModel } from '@migace/core';
import { PostgresqlSchemaReader, type Query } from '../src/index.js';
import { createDatabase } from './support.js';

const { schemaWith, read, query } = createDatabase();

async function modelOf(...sql: string[]): Promise<SchemaModel> {
    return read(await schemaWith(...sql));
}

// M2-AC-14, M2-AC-17
describe('Reading tables and columns', () => {
    test('a table has its columns with type, details, nullability and default', async () => {
        const model = await modelOf(`
            create table book (
              id          bigint         not null,
              title       varchar(200)   not null,
              price       numeric(12, 2) default 0,
              added_at    timestamp(3)   not null default now(),
              note        text,
              tags        text[]
            )`);

        expect(model.tables).toEqual([{
            name: 'book',
            columns: [
                { name: 'id', type: 'bigint', nullable: false },
                { name: 'title', type: 'character varying', typeDetails: '200', nullable: false },
                { name: 'price', type: 'numeric', typeDetails: '12,2', nullable: true, default: '0' },
                { name: 'added_at', type: 'timestamp without time zone', typeDetails: '3', nullable: false, default: 'now()' },
                { name: 'note', type: 'text', nullable: true },
                { name: 'tags', type: 'text[]', nullable: true },
            ],
            uniques: [], foreignKeys: [], checks: [], indexes: [], triggers: [],
        }]);
    });

    // M2-AC-04
    test('an identity column is marked, and its sequence is not listed', async () => {
        const model = await modelOf(`
            create table a (id bigint generated always as identity, n integer generated by default as identity)`);

        expect(model.tables[0].columns.map(column => [column.name, column.identity])).toEqual([['id', 'always'], ['n', 'by default']]);
        expect(model.sequences).toEqual([]);
    });

    test('comments on a table and on a column are read', async () => {
        const model = await modelOf(
            'create table customer (id bigint not null, mail varchar(255))',
            "comment on table customer is 'People who buy books'",
            "comment on column customer.mail is 'The e-mail address'");

        expect(model.tables[0].comment).toBe('People who buy books');
        expect(model.tables[0].columns[1].comment).toBe('The e-mail address');
    });

    // M2-AC-15
    test('only the named schema is read', async () => {
        await schemaWith('create table other (id bigint)');
        const model = await modelOf('create table mine (id bigint)');

        expect(model.tables.map(table => table.name)).toEqual(['mine']);
    });

    // M2-AC-16
    test('tables of the ledger are left out: by default those that start with mig_', async () => {
        const schema = await schemaWith('create table mig_run (id bigint primary key)', 'create table migration_plan (id bigint)', 'create table lg_run (id bigint)');

        expect((await read(schema)).tables.map(table => table.name)).toEqual(['lg_run', 'migration_plan']);
        expect((await read(schema, { ledgerPrefix: 'lg_' })).tables.map(table => table.name)).toEqual(['mig_run', 'migration_plan']);
    });
});

// M2-AC-17
describe('Reading constraints', () => {
    test('a primary key and a unique constraint with their columns in order', async () => {
        const model = await modelOf(`
            create table price (
              book_id bigint not null, currency varchar(3) not null, code varchar(10),
              primary key (currency, book_id),
              constraint uq_price_code unique (code)
            )`);

        expect(model.tables[0].primaryKey).toEqual({ name: 'price_pkey', columns: ['currency', 'book_id'] });
        expect(model.tables[0].uniques).toEqual([{ name: 'uq_price_code', columns: ['code'] }]);
    });

    // M2-AC-04
    test('the index behind a primary key or a unique constraint is not listed', async () => {
        const model = await modelOf('create table a (id bigint primary key, code varchar(10) unique)');

        expect(model.tables[0].indexes).toEqual([]);
    });

    test('a foreign key with its columns, its target and its actions', async () => {
        const model = await modelOf(
            'create table customer (id bigint primary key)',
            `create table orders (
              id bigint primary key,
              customer_id bigint not null,
              constraint fk_orders_customer foreign key (customer_id) references customer (id) on update restrict on delete cascade
            )`,
            'create table item (id bigint primary key, order_id bigint references orders on delete set null)');

        const table = (name: string) => model.tables.find(each => each.name === name)!;
        expect(table('orders').foreignKeys).toEqual([{
            name: 'fk_orders_customer', columns: ['customer_id'], target: 'customer', targetColumns: ['id'], onUpdate: 'restrict', onDelete: 'cascade',
        }]);
        expect(table('item').foreignKeys).toEqual([{
            name: 'item_order_id_fkey', columns: ['order_id'], target: 'orders', targetColumns: ['id'], onUpdate: 'no action', onDelete: 'set null',
        }]);
    });

    // M2-AC-18
    test('a check constraint with its expression as PostgreSQL returns it', async () => {
        const model = await modelOf(`
            create table review (stars integer constraint ck_review_stars check (stars between 1 and 5))`);

        expect(model.tables[0].checks).toEqual([{ name: 'ck_review_stars', expression: '((stars >= 1) AND (stars <= 5))' }]);
    });
});

// M2-AC-17, M2-AC-18
describe('Reading indexes', () => {
    test('an index with its columns, uniqueness and method', async () => {
        const model = await modelOf(
            'create table orders (id bigint, customer_id bigint, created_at timestamp)',
            'create index ix_orders_customer on orders (customer_id, created_at desc)',
            'create unique index ux_orders_id on orders (id)');

        expect(model.tables[0].indexes).toEqual([
            { name: 'ix_orders_customer', unique: false, method: 'btree', columns: ['customer_id', 'created_at DESC'] },
            { name: 'ux_orders_id', unique: true, method: 'btree', columns: ['id'] },
        ]);
    });

    // An operator class of an extension lives in another schema, so PostgreSQL writes it with that schema.
    test('an index on an expression, with a condition and with another method', async () => {
        const model = await modelOf(
            'create table book (id bigint, title varchar(200), stock integer)',
            'create index ix_book_title_lower on book (lower(title)) where stock > 0',
            'create index ix_book_title_search on book using gin (title gin_trgm_ops)');

        expect(model.tables[0].indexes).toEqual([
            { name: 'ix_book_title_lower', unique: false, method: 'btree', columns: ['lower((title)::text)'], condition: '(stock > 0)' },
            { name: 'ix_book_title_search', unique: false, method: 'gin', columns: ['title public.gin_trgm_ops'] },
        ]);
    });
});

// M2-AC-17
describe('Reading other objects', () => {
    test('a sequence', async () => {
        const model = await modelOf('create sequence bookshop_seq start with 1 increment by 50');

        expect(model.sequences).toEqual([
            { name: 'bookshop_seq', type: 'bigint', start: '1', increment: '50', min: '1', max: '9223372036854775807', cache: '1', cycle: false },
        ]);
    });

    // M2-AC-18
    test('a view with its definition as PostgreSQL returns it', async () => {
        const model = await modelOf(
            'create table orders (customer_id bigint, total_cents integer)',
            'create view v_order_totals as select o.customer_id, sum(o.total_cents) as total_cents from orders o group by o.customer_id',
            "comment on view v_order_totals is 'Totals per customer'");

        expect(model.views).toEqual([{
            name: 'v_order_totals',
            definition: ' SELECT customer_id,\n    sum(total_cents) AS total_cents\n   FROM orders o\n  GROUP BY customer_id;',
            comment: 'Totals per customer',
        }]);
    });

    test('a function and a procedure with arguments, result, language and body', async () => {
        const model = await modelOf(
            "create function vat(cents integer, rate numeric) returns integer language sql as $$ select (cents * rate)::integer $$",
            "create procedure clean_up() language plpgsql as $$ begin delete from pg_temp.nothing; end $$",
            "comment on function vat(integer, numeric) is 'Value added tax'");

        expect(model.routines).toEqual([
            { kind: 'procedure', name: 'clean_up', arguments: '', language: 'plpgsql', body: ' begin delete from pg_temp.nothing; end ' },
            { kind: 'function', name: 'vat', arguments: 'cents integer, rate numeric', returns: 'integer', language: 'sql', body: ' select (cents * rate)::integer ', comment: 'Value added tax' },
        ]);
    });

    test('a trigger with timing, events, level, function and condition', async () => {
        const model = await modelOf(
            'create table order_item (order_id bigint, quantity integer)',
            'create function refresh_order_total() returns trigger language plpgsql as $$ begin return null; end $$',
            'create trigger trg_order_item_total after insert or update or delete on order_item for each row execute function refresh_order_total()',
            'create trigger trg_order_item_check before update on order_item for each row when (new.quantity < 0) execute function refresh_order_total()',
            'create trigger trg_order_item_truncate after truncate on order_item for each statement execute function refresh_order_total()');

        expect(model.tables[0].triggers).toEqual([
            { name: 'trg_order_item_check', timing: 'before', events: ['update'], level: 'row', function: 'refresh_order_total()', condition: '(new.quantity < 0)' },
            { name: 'trg_order_item_total', timing: 'after', events: ['insert', 'delete', 'update'], level: 'row', function: 'refresh_order_total()' },
            { name: 'trg_order_item_truncate', timing: 'after', events: ['truncate'], level: 'statement', function: 'refresh_order_total()' },
        ]);
    });

    test('an enum type with its labels in order, and a domain with its checks', async () => {
        const model = await modelOf(
            "create type loyalty_level as enum ('BRONZE', 'SILVER', 'GOLD')",
            'create domain cents as integer not null default 0 constraint cents_not_negative check (value >= 0)');

        expect(model.enums).toEqual([{ name: 'loyalty_level', labels: ['BRONZE', 'SILVER', 'GOLD'] }]);
        expect(model.domains).toEqual([{
            name: 'cents', type: 'integer', nullable: false, default: '0', checks: [{ name: 'cents_not_negative', expression: '(VALUE >= 0)' }],
        }]);
    });

    test('extensions, without the objects that an extension brings along', async () => {
        const model = await modelOf('create extension if not exists pg_trgm');

        expect(model.extensions.map(extension => extension.name)).toContain('pg_trgm');
        expect(model.routines).toEqual([]);
    });
});

// M2-AC-19
describe('What the reader needs', () => {
    test('nothing but a function that runs a query and returns rows', async () => {
        const schema = await schemaWith('create table a (id bigint primary key)');
        const queries: Array<{ sql: string, parameters?: unknown[] }> = [];
        const recording: Query = (sql, parameters) => {
            queries.push({ sql, parameters });
            return query(sql, parameters);
        };

        const model = await new PostgresqlSchemaReader(recording, { schema }).read();

        expect(model.tables.map(table => table.name)).toEqual(['a']);
        expect(queries.length).toBeGreaterThan(0);
        expect(queries.every(each => /^\s*select\b/i.test(each.sql))).toBe(true);
    });

    // M2-AC-18
    test('the model does not depend on the search path of the connection, and the search path is left as it was', async () => {
        const schema = await schemaWith(
            'create table orders (customer_id bigint)',
            'create view v_orders as select o.customer_id from orders o');
        const inSearchPath = await read(schema);
        await query("select set_config('search_path', 'public', false)");

        const outsideSearchPath = await read(schema);

        expect(outsideSearchPath).toEqual(inSearchPath);
        expect(outsideSearchPath.views[0].definition).toBe(' SELECT customer_id\n   FROM orders o;');
        expect(await query("select current_setting('search_path') as path")).toEqual([{ path: 'public' }]);
    });

    test('a fake that returns no rows gives an empty model', async () => {
        const model = await new PostgresqlSchemaReader(async () => [], { schema: 'public' }).read();

        expect(model).toEqual({ tables: [], sequences: [], views: [], routines: [], enums: [], domains: [], extensions: [] });
    });
});
